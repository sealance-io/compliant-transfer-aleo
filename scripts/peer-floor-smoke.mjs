/**
 * Consumer-style guard for the `@provablehq/sdk` peer range floor.
 *
 * The SDK declares `@provablehq/sdk` as a peer dependency spanning two minor
 * lines. Only the upper line is installed in this repo, so nothing otherwise
 * proves the lower one still works. This script is copied into a throwaway
 * project that installs the packed SDK tarball against the floor version, and
 * asserts the Merkle roots are byte-identical to the ones produced by the
 * version the repo develops against.
 *
 * Poseidon4 hashing is the SDK's entire peer surface (see
 * packages/policy-engine-sdk/src/merkle-tree.ts), and a silent change there
 * would desync off-chain proofs from `merkle_tree.aleo` rather than throw, so
 * the roots are the thing worth pinning.
 *
 * Run from the scratch project root with PEER_FLOOR set to the exact version
 * under test.
 */

import { readFileSync } from "node:fs";
import { buildTree, generateLeaves } from "@sealance-io/policy-engine-aleo";

// Roots generated by @provablehq/sdk 0.11.9; any peer in range must reproduce them.
const EXPECTED_FIELD_ROOT = "2450516467948255117799903062613435776486030592463178904924209744526826223651";
const EXPECTED_ADDRESS_ROOT = "399400897550785983849339762182578475375497409589036881178997053979487606080";

const FIELD_LEAVES = ["0field", "1field", "2field", "3field"];
const ADDRESSES = [
  "aleo104ur4csap6qp3fguddw3mn7f6ddpfkn4clqzzkyjhxmw5j46xsrse6vt5f",
  "aleo193cgzzpr5lcwq6rmzq4l2ctg5f4mznead080mclfgrc0e5k0w5pstfdfps",
  "aleo194vjp7nt6pwgpruw3kz5fk5kvj9ur6sg2f4k84fqu6cpgq5xhvrs7emymc",
  "aleo1ashyu96tjwe63u0gtnnv8z5lhapdu4l5pjsl2kha7fv7hvz2eqxs5dz0rg",
];

const expectedPeer = process.env.PEER_FLOOR;
if (!expectedPeer) {
  console.error("PEER_FLOOR is not set - refusing to run a test that cannot confirm which peer it exercised");
  process.exit(1);
}

// Guard against a vacuous pass: if hoisting silently supplied a different
// version, the roots would match for the wrong reason.
const peerManifest = new URL("./node_modules/@provablehq/sdk/package.json", import.meta.url);
const resolvedPeer = JSON.parse(readFileSync(peerManifest, "utf8")).version;
if (resolvedPeer !== expectedPeer) {
  console.error(`Expected @provablehq/sdk ${expectedPeer}, but the scratch project resolved ${resolvedPeer}`);
  process.exit(1);
}

const fieldTree = buildTree(FIELD_LEAVES);
const addressTree = buildTree(generateLeaves(ADDRESSES));

const checks = [
  {
    name: "buildTree over literal fields",
    actual: fieldTree[fieldTree.length - 1].toString(),
    expected: EXPECTED_FIELD_ROOT,
  },
  {
    name: "buildTree over generateLeaves(addresses)",
    actual: addressTree[addressTree.length - 1].toString(),
    expected: EXPECTED_ADDRESS_ROOT,
  },
];

const failures = checks.filter(check => check.actual !== check.expected);
for (const check of checks) {
  const status = check.actual === check.expected ? "ok" : "FAILED";
  console.log(`${status}: ${check.name}`);
  if (check.actual !== check.expected) {
    console.error(`  expected ${check.expected}`);
    console.error(`  actual   ${check.actual}`);
  }
}

if (failures.length > 0) {
  console.error(
    `\n@provablehq/sdk ${resolvedPeer} produced different Merkle roots than the developed-against version. ` +
      `Narrow the peerDependencies range in packages/policy-engine-sdk/package.json instead of shipping a broken floor.`,
  );
  process.exit(1);
}

console.log(`\nPeer floor @provablehq/sdk ${resolvedPeer} reproduces all expected roots.`);
